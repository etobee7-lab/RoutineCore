/**
 * 특정 날짜가 한국 공휴일인지 판별합니다.
 * @param {string|Date} date - 'YYYY-MM-DD' 문자열 또는 Date 객체
 * @returns {boolean} 공휴일 여부
 */
function isKoreanHoliday(date) {
    let dateObj;
    let dateStr;

    if (date instanceof Date) {
        dateObj = date;
        const y = dateObj.getFullYear();
        const m = String(dateObj.getMonth() + 1).padStart(2, '0');
        const d = String(dateObj.getDate()).padStart(2, '0');
        dateStr = `${y}-${m}-${d}`;
    } else if (typeof date === 'string') {
        dateStr = date.trim();
        const parts = dateStr.split('-');
        if (parts.length !== 3) return false;
        dateObj = new Date(parseInt(parts[0]), parseInt(parts[1]) - 1, parseInt(parts[2]));
    } else {
        return false;
    }

    // 1. 주말 체크 (토요일: 6, 일요일: 0)
    const day = dateObj.getDay();
    if (day === 0 || day === 6) {
        return true;
    }

    // 2. 양력 고정 공휴일 체크 (MM-DD 추출)
    const monthDay = dateStr.substring(5); // 'MM-DD'
    if (FIXED_SOLAR_HOLIDAYS.has(monthDay)) {
        return true;
    }

    // 3. 음력 및 대체공휴일 체크
    if (MOVABLE_HOLIDAYS.has(dateStr)) {
        return true;
    }

    return false;
}

